"""TALK-01: the Lucide icons the Talk panel uses, copied from the approved prototype's sprite
(docs/prototypes/v04-approved/nextcloud-talk.html) into src/talk/icons.js.

    python3 -I tools/gen-talk-icons.py
"""
import json
import pathlib
import re
import sys

APP = pathlib.Path(__file__).resolve().parent.parent
PROTO = APP.parents[2] / "docs/prototypes/v04-approved/nextcloud-talk.html"
NAMES = [
    "layout-dashboard", "maximize-2", "minimize-2", "x", "panel-right", "plus", "file-text", "lock",
    "eye", "users", "locate", "save", "download", "triangle-alert", "refresh-cw", "copy",
    "message-square", "user-round-x", "ellipsis", "folder-open", "clock", "circle-check", "phone",
    "pencil", "share-2", "search",
]


def main() -> int:
    html = PROTO.read_text(encoding="utf-8")
    out = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright 2026 CasualOffice",
        "//",
        "// TALK-01 panel icons: Lucide (ISC licence, https://lucide.dev), from the approved prototype's",
        "// sprite. Generated by tools/gen-talk-icons.py; do not edit by hand.",
        "",
    ]
    missing = []
    for name in NAMES:
        m = re.search(r'<symbol id="i-%s"[^>]*>(.*?)</symbol>' % re.escape(name), html, re.S)
        if not m:
            missing.append(name)
            continue
        svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24">'
               '<g fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
               + re.sub(r"\s+", " ", m.group(1).strip()) + "</g></svg>")
        ident = re.sub(r"-(\w)", lambda g: g.group(1).upper(), name)
        out.append(f"export const {ident} = {json.dumps(svg)}")
    if missing:
        print("missing in the prototype sprite:", ", ".join(missing), file=sys.stderr)
        return 1
    (APP / "src/talk").mkdir(exist_ok=True)
    (APP / "src/talk/icons.js").write_text("\n".join(out) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
