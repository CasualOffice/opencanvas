# Writes src/icons.js from the approved prototype's SVG symbols:
#   python3 tools/gen-icons.py ../../../docs/prototypes/nextcloud-approved/NextcloudScreens.html src/icons.js
import re, sys, json
src, out = sys.argv[1], sys.argv[2]
s = open(src).read()
lucide = ['cloud-off', 'file-x', 'file-warning', 'lock', 'shield-alert', 'settings', 'refresh-cw', 'x', 'folder',
          'arrow-left', 'share-2', 'panel-right', 'more', 'download', 'circle-check', 'circle-x', 'circle-dashed',
          'triangle-alert', 'copy', 'rotate-ccw', 'info', 'eye', 'layout-template', 'external-link', 'maximize',
          'trash', 'ban', 'link', 'pencil', 'user', 'plug']
ft = {'ft-oc': 'ocanvas', 'ft-oc-db': 'ocanvasDatabase', 'ft-oc-wb': 'ocanvasWhiteboard'}

def camel(n):
    p = n.split('-')
    return p[0] + ''.join(x.title() for x in p[1:])

lines = ['// SPDX-License-Identifier: Apache-2.0', '// Copyright 2026 CasualOffice', '//',
         '// Icons as inline SVG strings, copied from the approved prototype',
         '// (docs/prototypes/nextcloud-approved/NextcloudScreens.html). Interface icons are Lucide',
         '// (ISC licence, https://lucide.dev); the .ocanvas file icons are ours (S2). Generated by tools/gen-icons.py; do not edit by hand.',
         '']
for n in lucide:
    m = re.search(r'<symbol id="i-%s" viewBox="([^"]+)">(.*?)</symbol>' % re.escape(n), s, re.S)
    if not m:
        sys.exit('missing ' + n)
    # The group carries the Lucide stroke style: NcIconSvgWrapper fills the <svg> element itself.
    svg = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s" width="24" height="24"><g fill="none" stroke="currentColor" '
           'stroke-width="2" stroke-linecap="round" stroke-linejoin="round">%s</g></svg>') % (m.group(1), m.group(2))
    lines.append('export const %s = %s' % (camel(n), json.dumps(svg)))
lines.append('')
for k, v in ft.items():
    m = re.search(r'<symbol id="%s" viewBox="([^"]+)">(.*?)</symbol>' % re.escape(k), s, re.S)
    svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="%s" width="32" height="32">%s</svg>' % (m.group(1), m.group(2))
    lines.append('export const %s = %s' % (v, json.dumps(svg)))
open(out, 'w').write('\n'.join(lines) + '\n')
