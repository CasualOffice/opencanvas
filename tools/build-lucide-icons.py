"""Build the full Lucide icon set for diagrams (DGM-17): a search index and path data per category.

Lucide is ISC (a few icons from Feather are MIT; icons/LICENSE-lucide.txt). Inputs, pinned to the
same version as the editor's lucide-react:

  - lucide-static@<version>: tags.json and icon-nodes.json (npm),
  - the Lucide repository at tag <version>: icons/<name>.json (categories) and categories/*.json
    (titles). No npm package ships the categories.

    python3 tools/build-lucide-icons.py --static <lucide-static dir> --repo <lucide repo dir>
    python3 tools/build-lucide-icons.py --check   # the output exists and matches lucide-react

Writes web/packages/board/src/lucide/index.json (names, tags, categories: what search needs) and
web/packages/board/src/lucide/paths/<category>.json (path data in a 24 x 24 box, stroked), each
icon in its first category's file. The editor loads them lazily; nothing is in the initial bundle
or the board chunk. Lucide 1.x has no brand logos; any name in BRAND is refused all the same.
"""
import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "web", "packages", "board", "src", "lucide")
PATH_RE = re.compile(r"[MLHVCSQTAZmlhvcsqtaz0-9 ,.\-]{1,2000}")
# Owner policy: nothing vendor-branded. Lucide removed brand icons in 1.0; keep the guard.
BRAND = re.compile(r"^(github|gitlab|figma|slack|twitter|facebook|instagram|youtube|linkedin|codepen|codesandbox|dribbble|framer|trello|twitch|chrome|chromium|pocket|rss-brand)$")
MAX_TAGS = 10


def f(v):
    v = round(float(v), 3)
    s = ("%f" % v).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def to_d(tag, a):
    g = lambda k: float(a.get(k, "0"))
    if tag == "path":
        return a["d"]
    if tag in ("circle", "ellipse"):
        cx, cy = g("cx"), g("cy")
        rx = g("r") if tag == "circle" else g("rx")
        ry = g("r") if tag == "circle" else g("ry")
        return f"M{f(cx - rx)} {f(cy)}a{f(rx)} {f(ry)} 0 1 0 {f(2 * rx)} 0a{f(rx)} {f(ry)} 0 1 0 {f(-2 * rx)} 0"
    if tag == "rect":
        x, y, w, h = g("x"), g("y"), g("width"), g("height")
        rx = float(a.get("rx", a.get("ry", "0")))
        ry = float(a.get("ry", a.get("rx", "0")))
        rx, ry = min(rx, w / 2), min(ry, h / 2)
        if rx <= 0:
            return f"M{f(x)} {f(y)}h{f(w)}v{f(h)}h{f(-w)}Z"
        return (f"M{f(x + rx)} {f(y)}h{f(w - 2 * rx)}a{f(rx)} {f(ry)} 0 0 1 {f(rx)} {f(ry)}v{f(h - 2 * ry)}"
                f"a{f(rx)} {f(ry)} 0 0 1 {f(-rx)} {f(ry)}h{f(-(w - 2 * rx))}a{f(rx)} {f(ry)} 0 0 1 {f(-rx)} {f(-ry)}"
                f"v{f(-(h - 2 * ry))}a{f(rx)} {f(ry)} 0 0 1 {f(rx)} {f(-ry)}Z")
    if tag == "line":
        return f"M{f(g('x1'))} {f(g('y1'))}L{f(g('x2'))} {f(g('y2'))}"
    if tag in ("polyline", "polygon"):
        nums = [f(v) for v in re.split(r"[\s,]+", a["points"].strip())]
        pts = [f"{nums[i]} {nums[i + 1]}" for i in range(0, len(nums), 2)]
        return "M" + "L".join(pts) + ("Z" if tag == "polygon" else "")
    raise SystemExit(f"unsupported element {tag}")


def lucide_react_version():
    pkg = os.path.join(ROOT, "web", "packages", "board", "package.json")
    v = json.load(open(pkg))["dependencies"]["lucide-react"]
    return v.lstrip("^~")


def build(static_dir, repo_dir):
    tags = json.load(open(os.path.join(static_dir, "tags.json")))
    nodes = json.load(open(os.path.join(static_dir, "icon-nodes.json")))
    version = json.load(open(os.path.join(static_dir, "package.json")))["version"]
    cats = {}
    for fn in sorted(os.listdir(os.path.join(repo_dir, "categories"))):
        if fn.endswith(".json"):
            cats[fn[:-5]] = json.load(open(os.path.join(repo_dir, "categories", fn)))["title"]
    cat_ids = sorted(cats)
    icons, paths = [], {c: {} for c in cat_ids}
    for name in sorted(nodes):
        if BRAND.match(name):
            continue
        meta = json.load(open(os.path.join(repo_dir, "icons", name + ".json")))
        ic = [c for c in meta.get("categories", []) if c in cats] or ["shapes"]
        ds = [to_d(t, a) for t, a in nodes[name]]
        if not ds or not all(PATH_RE.fullmatch(d) for d in ds):
            raise SystemExit(f"{name}: not plain path data")
        words = [t for t in tags.get(name, []) if isinstance(t, str)][:MAX_TAGS]
        icons.append([name, " ".join(words), [cat_ids.index(c) for c in ic]])
        paths[ic[0]][name] = ds
    os.makedirs(os.path.join(OUT, "paths"), exist_ok=True)
    index = {
        "$comment": "Generated by tools/build-lucide-icons.py from Lucide (ISC). Do not edit.",
        "version": version,
        "categories": [{"id": c, "name": cats[c], "count": sum(1 for i in icons if cat_ids.index(c) in i[2])} for c in cat_ids],
        "icons": icons,
    }
    with open(os.path.join(OUT, "index.json"), "w") as fh:
        json.dump(index, fh, separators=(",", ":"))
        fh.write("\n")
    for c in cat_ids:
        with open(os.path.join(OUT, "paths", c + ".json"), "w") as fh:
            json.dump(paths[c], fh, separators=(",", ":"))
            fh.write("\n")
    print(f"{len(icons)} icons in {len(cat_ids)} categories (Lucide {version})")


def check():
    p = os.path.join(OUT, "index.json")
    if not os.path.exists(p):
        sys.exit("lucide index missing: run tools/build-lucide-icons.py")
    idx = json.load(open(p))
    want = lucide_react_version()
    if idx["version"] != want:
        sys.exit(f"lucide index is {idx['version']}, lucide-react is {want}: regenerate")
    for c in idx["categories"]:
        if not os.path.exists(os.path.join(OUT, "paths", c["id"] + ".json")):
            sys.exit(f"missing paths/{c['id']}.json")
    if any(BRAND.match(i[0]) for i in idx["icons"]):
        sys.exit("a brand icon is in the index")
    print(f"lucide icons: ok ({len(idx['icons'])}, Lucide {idx['version']})")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--static")
    ap.add_argument("--repo")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        check()
    elif a.static and a.repo:
        build(a.static, a.repo)
    else:
        ap.error("give --static and --repo, or --check")
